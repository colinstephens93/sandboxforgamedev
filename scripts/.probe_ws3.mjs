import fs from 'node:fs';
import { startApp, openPage } from './lib/browser.mjs';
const app = await startApp();
const logs = [];
const { browser, page } = await openPage({ url: app.url, width: 800, height: 450, quality: 'medium', logs });
await page.waitForFunction(() => window.__game && window.__game.frames > 2, null, { timeout: 300000 });
await page.evaluate(() => { const g = window.__game; g.introT = 999; g.setMode('walk'); g.mode = 'fixed'; g.prepare({ engine: true, seat: true }); g.cam([-0.406, 1.40, 0.876], [-0.41, 1.12, -0.2], 64); });
await page.waitForTimeout(600);
const shot = async (n) => { const d = await page.evaluate(() => { const g = window.__game; g.paused = true; g.R.render(0.016); return g.canvas.toDataURL('image/png'); }); fs.writeFileSync(`.dev/${n}.png`, Buffer.from(d.split(',')[1], 'base64')); };
await shot('ws2_on');
await page.evaluate(() => { const g = window.__game; g.truck.group.traverse((o) => { if (o.isMesh && o.name === 'windshield') o.visible = false; }); });
await shot('ws2_off');
await browser.close(); await app.close();
